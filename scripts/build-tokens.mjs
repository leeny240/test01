// Generates src/styles/tokens.css from tokens/tokens.json (exported from Figma variables).
// Desktop mode is the default; mobile mode applies under [data-mode="mobile"] and on narrow screens.
import { readFileSync, writeFileSync } from 'node:fs'

const SRC = new URL('../tokens/tokens.json', import.meta.url)
const OUT = new URL('../src/styles/tokens.css', import.meta.url)
const MOBILE_QUERY = '(max-width: 640px)'

const tokens = JSON.parse(readFileSync(SRC, 'utf8'))

// Mirrors the WEB code syntax set on each Figma variable, e.g. color/bg/canvas -> --color-bg-canvas.
function cssName(path) {
  const [root, ...rest] = path
  if (root === 'typography' && rest[0] === 'font-family') return `--font-${rest[1]}`
  const parts = root === 'primitives' || root === 'typography' || root === 'component' ? rest : path
  return `--${parts.join('-')}`
}

const leaves = new Map()
function walk(node, path) {
  if (node && typeof node === 'object' && '$value' in node) {
    leaves.set(path.join('.'), { path, token: node })
    return
  }
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$') || key === 'textStyles') continue
    walk(child, [...path, key])
  }
}
walk(tokens, [])

function cssValue(value, type) {
  if (typeof value === 'string' && value.startsWith('{')) {
    const ref = value.slice(1, -1)
    const target = leaves.get(ref)
    if (!target) throw new Error(`Unknown token reference: ${value}`)
    return `var(${cssName(target.path)})`
  }
  if (type === 'fontFamily') return `'${value}', system-ui, -apple-system, sans-serif`
  if (type === 'color') return value.toLowerCase()
  return String(value)
}

const base = []
const mobile = []
for (const { path, token } of leaves.values()) {
  const name = cssName(path)
  base.push(`  ${name}: ${cssValue(token.$value, token.$type)};`)
  const mobileValue = token.$extensions?.modes?.mobile
  if (mobileValue !== undefined && mobileValue !== token.$value) {
    mobile.push(`  ${name}: ${cssValue(mobileValue, token.$type)};`)
  }
}

const textStyles = Object.entries(tokens.textStyles).map(([name, { $value: v }]) =>
  [
    `.text-${name} {`,
    `  font-family: ${cssValue(v.fontFamily, 'fontFamily')};`,
    `  font-size: ${cssValue(v.fontSize, 'dimension')};`,
    `  font-weight: ${v.fontWeight};`,
    `  line-height: ${v.lineHeight};`,
    '}',
  ].join('\n'),
)

const css = [
  '/* Generated by scripts/build-tokens.mjs from tokens/tokens.json — do not edit by hand. */',
  '',
  ':root {',
  ...base,
  '}',
  '',
  '[data-mode="mobile"] {',
  ...mobile,
  '}',
  '',
  `@media ${MOBILE_QUERY} {`,
  '  :root:not([data-mode="desktop"]) {',
  ...mobile.map((line) => `  ${line}`),
  '  }',
  '}',
  '',
  ...textStyles.flatMap((block) => [block, '']),
].join('\n')

writeFileSync(OUT, css)
console.log(`tokens.css: ${base.length} variables, ${mobile.length} mobile overrides, ${textStyles.length} text styles`)
